"""Writes THIRD_PARTY_LICENSES from the Rust crates in the binaries, or checks the files.

Each binary gets its own file, for the platform it is built for: THIRD_PARTY_LICENSES for
Kudari on Linux, THIRD_PARTY_LICENSES-windows for the Windows package, which links crates
that Linux does not.
"""

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LICENSE_FILES = ("license", "licence", "copying", "notice", "unlicense")
TARGETS = [
    {
        "output": ROOT / "THIRD_PARTY_LICENSES",
        "package": "kudari",
        "platform": "x86_64-unknown-linux-gnu",
        "header": """Kudari contains the following Rust crates. Their licenses are reproduced here as
they require. This file is generated by tools/third_party_licenses.py.

Qt and KDE Frameworks are linked dynamically and are not part of the binary.
""",
    },
    {
        "output": ROOT / "THIRD_PARTY_LICENSES-windows",
        "package": "kudari-windows",
        "platform": "x86_64-pc-windows-msvc",
        "header": """Kudari for Windows contains the following Rust crates. Their licenses are
reproduced here as they require. This file is generated by
tools/third_party_licenses.py.

Qt is linked dynamically and is not part of the program.
""",
    },
]


def runtime_crates(target):
    """The crates reachable from the package through normal dependencies, without build
    tools, on the platform of the target."""
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target["platform"]],
            cwd=ROOT,
        )
    )
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    packages = {package["id"]: package for package in metadata["packages"]}
    root = next(
        package["id"]
        for package in metadata["packages"]
        if package["name"] == target["package"] and package["id"] in metadata["workspace_members"]
    )
    pending = [root]
    seen = set()
    while pending:
        current = pending.pop()
        if current not in seen:
            seen.add(current)
            for dependency in nodes[current]["deps"]:
                if any(kind["kind"] is None for kind in dependency["dep_kinds"]):
                    pending.append(dependency["pkg"])
    # The crates of the workspace are Kudari itself.
    seen.difference_update(metadata["workspace_members"])
    return sorted((packages[crate] for crate in seen), key=lambda package: (package["name"], package["version"]))


def linked_crates(target):
    """The crates that Cargo builds into the package for the platform, as `cargo tree`
    finds them: a second way to the same list, for the check."""
    output = subprocess.check_output(
        ["cargo", "tree", "--locked", "--quiet", "--package", target["package"], "--target", target["platform"],
         "--edges", "normal", "--prefix", "none", "--format", "{p}"],
        cwd=ROOT,
        text=True,
    )
    members = {
        package["name"]
        for package in json.loads(
            subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked", "--no-deps"], cwd=ROOT)
        )["packages"]
    }
    crates = set()
    for line in output.splitlines():
        match = re.match(r"(\S+) v(\S+)", line)
        if match and match[1] not in members:
            crates.add((match[1], match[2]))
    return crates


def license_texts(package):
    """The license files a crate ships."""
    directory = pathlib.Path(package["manifest_path"]).parent
    files = [path for path in sorted(directory.iterdir()) if path.is_file() and path.name.lower().startswith(LICENSE_FILES)]
    return [path.read_text(errors="replace").strip() for path in files]


def render(target):
    crates = runtime_crates(target)
    texts = {}
    without_text = []
    lines = [target["header"], f"Crates ({len(crates)}):\n"]
    for crate in crates:
        lines.append(f"  {crate['name']} {crate['version']}: {crate['license']}")
        found = license_texts(crate)
        if not found:
            without_text.append(crate)
        for text in found:
            texts.setdefault(text, []).append(crate["name"])
    for crate in without_text:
        for identifier in sorted(set(crate["license"].replace("(", " ").replace(")", " ").split()) - {"OR", "AND", "WITH"}):
            standard = pathlib.Path("/usr/share/licenses/spdx") / f"{identifier}.txt"
            if standard.exists():
                texts.setdefault(standard.read_text().strip(), []).append(crate["name"])
    for text, names in texts.items():
        lines += ["", "=" * 78, "Used by: " + ", ".join(sorted(set(names))), "=" * 78, "", text]
    return "\n".join(lines) + "\n", without_text


def listed_crates(content):
    """The crates that a file of licenses names."""
    return {(match[1], match[2]) for match in re.finditer(r"^  (\S+) (\S+): ", content, re.M)}


def main():
    for target in TARGETS:
        content, without_text = render(target)
        output = target["output"]
        if "--check" in sys.argv:
            if not output.exists() or output.read_text() != content:
                sys.exit(f"{output.name} is out of date: run tools/third_party_licenses.py")
            missing = linked_crates(target) - listed_crates(content)
            if missing:
                names = ", ".join(f"{name} {version}" for name, version in sorted(missing))
                sys.exit(f"{output.name} leaves out crates that {target['package']} links: {names}")
            continue
        output.write_text(content)
        print(f"{output.name}: {content.count(chr(10))} lines; standard text used for: "
              f"{[crate['name'] for crate in without_text]}")


if __name__ == "__main__":
    main()
