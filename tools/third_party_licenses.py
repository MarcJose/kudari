"""Writes THIRD_PARTY_LICENSES from the Rust crates in the binary, or checks the file."""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "THIRD_PARTY_LICENSES"
LICENSE_FILES = ("license", "licence", "copying", "notice", "unlicense")
HEADER = """Kudari contains the following Rust crates. Their licenses are reproduced here as
they require. This file is generated by tools/third_party_licenses.py.

Qt and KDE Frameworks are linked dynamically and are not part of the binary.
"""


def runtime_crates():
    """The crates reachable through normal dependencies, without build tools."""
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", "x86_64-unknown-linux-gnu"],
            cwd=ROOT,
        )
    )
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    packages = {package["id"]: package for package in metadata["packages"]}
    pending = [metadata["resolve"]["root"]]
    seen = set()
    while pending:
        current = pending.pop()
        if current not in seen:
            seen.add(current)
            for dependency in nodes[current]["deps"]:
                if any(kind["kind"] is None for kind in dependency["dep_kinds"]):
                    pending.append(dependency["pkg"])
    # The crates of the workspace are Kudari itself.
    seen.difference_update(metadata["workspace_members"])
    return sorted((packages[crate] for crate in seen), key=lambda package: (package["name"], package["version"]))


def license_texts(package):
    """The license files a crate ships."""
    directory = pathlib.Path(package["manifest_path"]).parent
    files = [path for path in sorted(directory.iterdir()) if path.is_file() and path.name.lower().startswith(LICENSE_FILES)]
    return [path.read_text(errors="replace").strip() for path in files]


def render():
    crates = runtime_crates()
    texts = {}
    without_text = []
    lines = [HEADER, f"Crates ({len(crates)}):\n"]
    for crate in crates:
        lines.append(f"  {crate['name']} {crate['version']}: {crate['license']}")
        found = license_texts(crate)
        if not found:
            without_text.append(crate)
        for text in found:
            texts.setdefault(text, []).append(crate["name"])
    for crate in without_text:
        for identifier in sorted(set(crate["license"].replace("(", " ").replace(")", " ").split()) - {"OR", "AND", "WITH"}):
            standard = pathlib.Path("/usr/share/licenses/spdx") / f"{identifier}.txt"
            if standard.exists():
                texts.setdefault(standard.read_text().strip(), []).append(crate["name"])
    for text, names in texts.items():
        lines += ["", "=" * 78, "Used by: " + ", ".join(sorted(set(names))), "=" * 78, "", text]
    return "\n".join(lines) + "\n", without_text


def main():
    content, without_text = render()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            sys.exit("THIRD_PARTY_LICENSES is out of date: run tools/third_party_licenses.py")
        return
    OUTPUT.write_text(content)
    print(f"{content.count(chr(10))} lines; standard text used for: {[crate['name'] for crate in without_text]}")


if __name__ == "__main__":
    main()
